package com.toblad.khwab.ui.theme

/**
 * Represents the active visual theme
 * used by the Khwab application.
 *
 * DEFAULT
 *     Uses the standard Khwab theme.
 *
 * AURA
 *     Uses the Aura generated theme.
 */
enum class ThemeMode {

    /**
     * Default Khwab appearance.
     */
    DEFAULT,

    /**
     * Aura powered appearance.
     */
    AURA
}
